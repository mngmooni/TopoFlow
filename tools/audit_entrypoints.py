"""Static, read-only entrypoint inventory; never imports experiment modules.

The classifications are deliberately conservative. A detected name or call is a
*potential* dependency; a static scan cannot prove an experiment reproducible.
"""
from __future__ import annotations

import argparse
import ast
import json
from dataclasses import asdict, dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT_EXTS = {".pkl", ".pt", ".ckpt", ".npz"}


@dataclass(frozen=True)
class Entry:
    path: str
    main_guard: bool
    potential_import_time_work: bool
    reads_pickle: bool
    reads_torch: bool
    reads_numpy: bool
    references_results_tree: bool
    potential_write_operations: bool
    subprocess_calls: bool
    linux_specific: bool


def call_name(node: ast.AST) -> str:
    if not isinstance(node, ast.Call):
        return ""
    try:
        return ast.unparse(node.func)
    except (TypeError, ValueError):
        return ""


def is_main_guard(node: ast.AST) -> bool:
    if not isinstance(node, ast.If):
        return False
    test = node.test
    if not isinstance(test, ast.Compare) or len(test.ops) != 1 or not isinstance(test.ops[0], ast.Eq):
        return False
    if len(test.comparators) != 1:
        return False
    parts = (test.left, test.comparators[0])
    return any(isinstance(x, ast.Name) and x.id == "__name__" for x in parts) and any(
        isinstance(x, ast.Constant) and x.value == "__main__" for x in parts
    )



def may_evaluate_at_import(node: ast.AST) -> bool:
    if isinstance(node, (ast.Import, ast.ImportFrom, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef,
                         ast.Pass)):
        return False
    if is_main_guard(node):
        return False
    if isinstance(node, (ast.Assign, ast.AnnAssign)):
        value = node.value
        return value is not None and any(isinstance(x, ast.Call) for x in ast.walk(value))
    if isinstance(node, ast.Expr):
        return not isinstance(node.value, ast.Constant)

    control_flow_nodes = (
        ast.For,
        ast.AsyncFor,
        ast.While,
        ast.If,
        ast.With,
        ast.AsyncWith,
        ast.Try,
        ast.Raise,
        ast.AugAssign,
    )

    if hasattr(ast, "TryStar"):
        control_flow_nodes += (ast.TryStar,)

    return isinstance(node, control_flow_nodes)


def audit_file(path: Path, root: Path = ROOT) -> Entry:
    src = path.read_text(encoding="utf-8")
    tree = ast.parse(src, filename=str(path))
    calls = {call_name(n) for n in ast.walk(tree) if isinstance(n, ast.Call)}
    reads_pickle = bool(calls & {"pickle.load", "pickle.loads"})
    reads_torch = bool(calls & {"torch.load"})
    reads_numpy = bool(calls & {"np.load", "numpy.load"})
    write_names = {"torch.save", "np.save", "np.savez", "np.savez_compressed", "json.dump",
                   "pickle.dump", "plt.savefig", "fig.savefig", "subprocess.run", "subprocess.Popen"}
    possible_write = bool(calls & write_names) or any(
        isinstance(n, ast.Call) and call_name(n) in {"open", "Path.open"} and any(
            isinstance(a, ast.Constant) and isinstance(a.value, str) and any(ch in a.value for ch in "wax+")
            for a in list(n.args[1:2]) + [kw.value for kw in n.keywords if kw.arg == "mode"]
        ) for n in ast.walk(tree)
    )
    return Entry(
        path=path.relative_to(root).as_posix(),
        main_guard=any(is_main_guard(n) for n in tree.body),
        potential_import_time_work=any(may_evaluate_at_import(n) for n in tree.body),
        reads_pickle=reads_pickle,
        reads_torch=reads_torch,
        reads_numpy=reads_numpy,
        references_results_tree="results/" in src,
        potential_write_operations=possible_write,
        subprocess_calls=bool(calls & {"subprocess.run", "subprocess.Popen", "os.system"}),
        linux_specific=("/proc/cpuinfo" in src or "os.uname(" in src),
    )


def audit_repo(root: Path = ROOT) -> dict:
    files = sorted(p for p in (root / "experiments").rglob("*.py") if p.name != "__init__.py")
    entries = [audit_file(p, root) for p in files]
    counts = {suffix: len(list((root / "results").rglob("*" + suffix))) for suffix in sorted(INPUT_EXTS)}
    return {
        "scope": "static inspection only; scripts were not imported or executed",
        "experiment_scripts": len(entries),
        "archived_raw_input_counts": counts,
        "main_guard_count": sum(e.main_guard for e in entries),
        "possible_import_time_work_count": sum(e.potential_import_time_work for e in entries),
        "pickle_read_call_count": sum(e.reads_pickle for e in entries),
        "torch_read_call_count": sum(e.reads_torch for e in entries),
        "numpy_read_call_count": sum(e.reads_numpy for e in entries),
        "entries": [asdict(e) for e in entries],
    }


def to_markdown(data: dict) -> str:
    d = data
    head = [
        "# Experiment entrypoint inventory (static audit)", "",
        "This report is generated by `python -m tools.audit_entrypoints --format markdown`. It parses source code",
        "without importing, running, training, or modifying any experiment. **Static hints are not execution guarantees.**",
        "", f"- Experiment scripts inventoried: **{d['experiment_scripts']}** (excluding package `__init__.py`).",
        f"- Explicit `__main__` guards: **{d['main_guard_count']}**.",
        f"- Potential import-time expressions/control flow: **{d['possible_import_time_work_count']}** (conservative heuristic).",
        f"- Scripts calling `pickle.load`: **{d['pickle_read_call_count']}**; `torch.load`: **{d['torch_read_call_count']}**; `numpy.load`: **{d['numpy_read_call_count']}**.",
        "- Raw input files currently under `results/`: " + ", ".join(
            f"`{k}` **{n}**" for k, n in d["archived_raw_input_counts"].items()
        ) + ".", "",
        "**How to read the table:** ✓ means the static marker was found; — means it was not found. ",
        "`I/O at import` is a heuristic flag and may include benign setup; it is not a proof of side effects.",
        "Paths inside scripts are generally resolved relative to the current working directory. ",
        "Run commands from the repository root unless a tool explicitly supports arbitrary directories.", "",
        "| Entrypoint | `__main__` | Potential import work | pickle read | checkpoint load | NumPy load | Potential writes | OS-specific |",
        "|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|",
    ]
    def ck(x: bool) -> str: return "✓" if x else "—"
    for e in d["entries"]:
        head.append("| `"+e["path"]+"` | "+" | ".join(ck(e[k]) for k in (
            "main_guard", "potential_import_time_work", "reads_pickle", "reads_torch",
            "reads_numpy", "potential_write_operations", "linux_specific")) + " |")
    head += ["", "## Scope and limitations", "",
             "- Some dynamically constructed filenames and indirect function calls are not detected by these flags.",
             "- The absence of a `.pkl`, `.pt`, `.npz`, or `.ckpt` file here does not prove that source data cannot be regenerated externally.",
             "- A script that creates missing prerequisites is not necessarily runnable without first following its pipeline.",
             "- Scripts that write outputs may overwrite curated results; use a scratch copy for any unverified experiment run.",
             "- To test actual reproducibility, restore original splits/checkpoints or regenerate them under recorded settings and re-run analyses.", ""]
    return "\n".join(head)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--format", choices=("summary", "json", "markdown"), default="summary")
    p.add_argument("--output", type=Path, help="Optional output file (none means stdout)")
    p.add_argument("--root", type=Path, default=ROOT, help="Repository root to inspect")
    args = p.parse_args()
    data = audit_repo(args.root.resolve())
    if args.format == "json":
        rendered = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    elif args.format == "markdown":
        rendered = to_markdown(data)
    else:
        rendered = (f"Experiment scripts: {data['experiment_scripts']}\n"
                    f"Main guards: {data['main_guard_count']}\n"
                    f"Potential import-time work: {data['possible_import_time_work_count']}\n"
                    f"Raw inputs under results/: {data['archived_raw_input_counts']}\n"
                    "Static only; no experiment module executed.\n")
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
    else:
        print(rendered, end="" if rendered.endswith("\n") else "\n")


if __name__ == "__main__":
    main()
